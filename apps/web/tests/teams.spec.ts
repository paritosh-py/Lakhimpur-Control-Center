import {test,expect} from '@playwright/test';

test('exercise dispatch reaches Team App, updates map, survives reload and isolates reset',async({page,context,request})=>{
  test.setTimeout(60000);
  // Wi-Fi HTTP lacks randomUUID; exercise the secure-random fallback.
  await context.addInitScript(() => Object.defineProperty(crypto, "randomUUID", {value:undefined, configurable:true}));
  await request.post('/api/scenario/stop');
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Replay & exercises',exact:true}).click();
  await page.getByRole('button',{name:'Load synthetic exercise'}).click();
  await expect(page.locator('.exercise-banner')).toContainText('Step 1');
  await page.getByRole('button',{name:'Teams & assignments',exact:true}).click();
  const add=page.locator('form').filter({has:page.getByRole('heading',{name:'Add a team',exact:true})});
  await add.getByLabel('Team name',{exact:true}).fill('Team A');
  await add.getByRole('combobox',{name:'Current location',exact:true}).selectOption({label:'Kadam'});
  await add.getByRole('button',{name:'Add team',exact:true}).click();
  await expect(page.getByRole('link',{name:'Open Team App — Team A'})).toBeVisible();
  const assign=page.locator('form').filter({has:page.getByRole('heading',{name:'Assign a settlement',exact:true})});
  await assign.getByRole('combobox',{name:'Target settlement',exact:true}).selectOption({label:'Kadam'});
  await assign.getByRole('combobox',{name:'Available team',exact:true}).selectOption({index:1});
  await assign.getByLabel('Task instructions',{exact:true}).fill('Assess floodwater near Kadam and report access conditions.');
  await assign.getByRole('button',{name:'Assign team',exact:true}).click();
  await expect(page.locator('.team-task')).toHaveCount(1);
  await expect(page.locator('.team-task')).toContainText('assigned');
  await expect(assign.getByRole('combobox',{name:'Available team',exact:true})).toHaveValue('');
  await page.screenshot({path:'../../docs/screenshots/teams-desktop.png',fullPage:true});
  const href=await page.getByRole('link',{name:'Open Team App — Team A'}).getAttribute('href');
  const team=await context.newPage();await team.goto(href!);
  await expect(team.getByRole('heading',{name:'Assignment: Kadam'})).toBeVisible();
  await expect(team.getByText('EXERCISE TEAM APP · NOT LIVE',{exact:true})).toBeVisible();
  await team.getByRole('button',{name:'accepted',exact:true}).click();
  await expect(team.getByRole('button',{name:'en route',exact:true})).toBeEnabled();
  await team.getByRole('button',{name:'en route',exact:true}).click();
  await expect(team.getByRole('button',{name:'arrived',exact:true})).toBeEnabled();
  await expect(page.locator('.team-task')).toContainText('en route',{timeout:10000});
  await page.getByRole('button',{name:'Locate assignment'}).click();
  await expect(page.locator('.assignment-marker')).toContainText('Team A: en route');
  await expect(page.locator('.live-details')).toContainText('Team A: en route');
  await team.getByLabel('Status message').fill('Water across the approach road; awaiting control center review.');
  await team.getByRole('button',{name:'Report road blocked'}).click();
  await expect(team.getByRole('button',{name:'Resume travel'})).toBeEnabled();
  await page.getByRole('button',{name:'Teams & assignments',exact:true}).click();
  await expect(page.locator('.team-task')).toContainText('Assignment remains reserved',{timeout:10000});
  await page.reload();
  await expect(page.getByText('LIVE MONITORING',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Replay & exercises',exact:true}).click();
  await expect(page.locator('.exercise-banner')).toContainText('Step 1');
  await page.getByRole('button',{name:'Teams & assignments',exact:true}).click();
  await expect(page.locator('.team-task')).toContainText('blocked');
  await team.setViewportSize({width:390,height:844});
  expect(await team.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await team.screenshot({path:'../../docs/screenshots/team-app-mobile.png',fullPage:true});
  await team.getByLabel('Status message').fill('Resuming after operator instruction.');
  await team.getByRole('button',{name:'Resume travel'}).click();
  await expect(team.getByRole('button',{name:'arrived',exact:true})).toBeEnabled();
  await team.getByRole('button',{name:'arrived',exact:true}).click();
  await expect(team.getByRole('button',{name:'completed',exact:true})).toBeEnabled();
  await team.getByRole('button',{name:'completed',exact:true}).click();
  await expect(team.getByRole('heading',{name:'No active assignment'})).toBeVisible();
  await expect(page.locator('.team-task').getByText('completed',{exact:true}).first()).toBeVisible({timeout:10000});
  await page.getByRole('button',{name:'Reset replay'}).click();
  await expect(page.locator('.team-task')).toHaveCount(0);
  await expect(team.getByText(/This exercise has ended or was reset/)).toBeVisible({timeout:10000});
  await page.getByRole('button',{name:'Return to live'}).click();
  await page.getByRole('button',{name:'Teams & assignments',exact:true}).click();
  await expect(page.locator('.team-task')).toHaveCount(0);
  expect(errors).toEqual([]);await team.close();
});
